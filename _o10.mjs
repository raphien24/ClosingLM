import { createWorker } from "tesseract.js";
import sharp from "sharp";
import fs from "fs";
const buf = fs.readFileSync("C:/Users/rafia/Downloads/Screenshot_10.png");
const meta = await sharp(buf).metadata();
const origW = meta.width || 1280;
let tw = origW;
if (origW < 2000) tw = Math.min(3200, origW * 2); else if (origW > 3200) tw = 3200;
const processed = await sharp(buf).resize({ width: tw, withoutEnlargement: true }).grayscale().normalize().sharpen({ sigma: 1.0 }).png({ compressionLevel: 1 }).toBuffer();
console.log("META w="+origW+" h="+meta.height+" target="+tw);
const worker = await createWorker("eng", 1, { logger: () => {}, langPath: process.cwd(), cachePath: process.cwd() });
await worker.setParameters({ tessedit_pageseg_mode: "6", tessedit_char_whitelist: "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz.,%()-/: ", preserve_interword_spaces: "1" });
const { data } = await worker.recognize(processed);
console.log("=== PSM6 TEXT ===");
console.log(data.text);
console.log("=== conf "+data.confidence+" ===");
await worker.terminate();
